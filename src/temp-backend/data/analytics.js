/**
 * Generates Top Posts for analytics view based on MASTER_POSTS
 */
export function getTopPostsForRange(range = 'range-30d') {
  // Published posts sorted by impressions or engagement
  const published = MASTER_POSTS.filter((p) => p.status === 'published' || p.impressions);
  return published.map((p) => ({
    id: p.id,
    title: p.title,
    excerpt: p.excerpt || p.content.slice(0, 90) + '...',
    author: p.author,
    authorInitials: p.authorInitials,
    publishedDate: p.publishedDate || 'Recent',
    impressions: p.impressions || 12000,
    reactions: p.reactions || 350,
    comments: p.comments || p.commentsCount || 45,
    reposts: p.reposts || 20,
    engRate: p.engRate || p.engagementRate || 5.0,
    trend: p.trend || 'up',
    category: p.category,
    visualFormat: p.visualFormat || 'image',
  }));
}
